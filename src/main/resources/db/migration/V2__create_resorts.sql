CREATE TABLE resorts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id         BIGINT,
    name                VARCHAR(255)     NOT NULL,
    country             VARCHAR(255)     NOT NULL,
    continent           VARCHAR(255),
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    price               INTEGER,
    season              VARCHAR(255),
    highest_point       INTEGER,
    lowest_point        INTEGER,
    beginner_slopes     INTEGER,
    intermediate_slopes INTEGER,
    difficult_slopes    INTEGER,
    total_slopes        INTEGER,
    longest_run         INTEGER,
    snow_cannons        INTEGER,
    surface_lifts       INTEGER,
    chair_lifts         INTEGER,
    gondola_lifts       INTEGER,
    total_lifts         INTEGER,
    lift_capacity       INTEGER,
    child_friendly      BOOLEAN,
    snowparks           BOOLEAN,
    nightskiing         BOOLEAN,
    summer_skiing       BOOLEAN,
    active              BOOLEAN          NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP        NOT NULL,
    updated_at          TIMESTAMP        NOT NULL,
    CONSTRAINT uq_resorts_external_id UNIQUE (external_id)
);
